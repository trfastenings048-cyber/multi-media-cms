const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const source = path.join(__dirname, 'dist', 'XOS-Setup.exe')
const destination = path.join(__dirname, '..', 'public', 'XOS-Setup.exe')
fs.copyFileSync(source, destination)
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
if (hash(source) !== hash(destination)) throw new Error('Published executable does not match build')
console.log(`Published ${destination}\nSHA256 ${hash(destination)}`)
